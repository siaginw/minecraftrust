from replay import Adapter, Limits, ReplayError, file_sha, digest

def require(ok,reason):
    if not ok:raise RuntimeError(reason)

def boundary(row,binding,step):
    expected=dict(schema="STATE_DIFF_BOUNDARY_V1",**binding,step=step,qualification="OFFLINE_MODEL_ONLY",production_authority=False)
    if not isinstance(row,dict) or set(row)!=set(expected)|{"status","error","generation","values","effects"}:raise ReplayError("boundary schema")
    if any(type(row[k]) is not type(v) or row[k]!=v for k,v in expected.items()):raise ReplayError("boundary binding")
    if row["status"] not in (("INITIAL",) if step==0 else ("COMMITTED","REJECTED")) or type(row["generation"]) is not int or not 0<=row["generation"]<=1000:raise ReplayError("status/generation")
    if not isinstance(row["values"],list) or len(row["values"])!=16 or any(type(x) is not int or not 0<=x<=65535 for x in row["values"]):raise ReplayError("values schema")
    if not isinstance(row["effects"],list) or len(row["effects"])>16 or any(not isinstance(e,list) or len(e)!=3 or any(type(x) is not int for x in e) or not 0<=e[0]<16 or any(not 0<=x<=65535 for x in e[1:]) for e in row["effects"]):raise ReplayError("effects schema")
    if row["status"]=="REJECTED" and (row["error"] not in ("CELL","COUNT","RANGE") or row["effects"]):raise ReplayError("rejected operation effects")
    if row["status"] in ("COMMITTED","INITIAL") and row["error"] is not None:raise ReplayError("successful error")
    if step==0 and (row["generation"]!=0 or row["effects"]):raise ReplayError("initial state must be immutable")
    return row

def run_case(name,commands,values,reference,candidate,root,expected_divergence=False):
    require(1<=len(commands)<=1000,"command budget")
    # These immutable tuples are generated by this campaign, not arbitrary user
    # text. Explicit versioning limits the adapter to the three pure operations.
    commands=tuple(commands);values=tuple(values)
    binding=dict(session=uuid.uuid4().hex,challenge=secrets.token_hex(32),trace_sha256=digest(dict(commands=commands,values=values)))
    folder=root/binding["session"];folder.mkdir(parents=True,exist_ok=False)
    (folder/"input.json").write_text(json.dumps(dict(name=name,binding=binding,commands=commands,values=values),indent=2)+"\n",encoding="utf-8")
    initial=" ".join(["INIT","STATE_DIFF_MODEL_V1",binding["session"],binding["challenge"],binding["trace_sha256"],",".join(map(str,values))])
    adapters=[];first=None;last=None;paired=0;consumed=0;issued=0;start=time.perf_counter()
    try:
        for label,command in (("reference",reference),("candidate",candidate)):adapters.append(Adapter(command,folder,label))
        for adapter in adapters:adapter.send(initial)
        for step,text in enumerate(("INIT",*commands)):
            issued=step
            if step:
                for adapter in adapters:adapter.send(text)
            rows=[]
            for adapter in adapters:
                raw=adapter.receive(remaining_budget=Limits().boundary_bytes-consumed);consumed+=adapter.last_line_bytes
                rows.append(boundary(raw,binding,step))
            paired+=1
            if rows[0]!=rows[1]:
                first=dict(step=step,command=text,reference=rows[0],candidate=rows[1]);break
            last=rows[0]
    except (ReplayError,OSError) as error:first=dict(step=issued,kind="ADAPTER_ERROR",detail=str(error))
    finally:processes=[adapter.close(abort=first is not None) for adapter in adapters]
    if first is None:
        for process in processes:
            if process["exit"]!=0 or process["stderr_bytes"] or process["extra_stdout_lines"] or process["resource_error"]:first=dict(step=issued,kind="ADAPTER_TERMINATION",detail=process);break
    result=dict(schema="STATE_DIFF_COMPARISON_V1",name=name,status="PASS" if first is None else "DIVERGED",expected_divergence=expected_divergence,scope="OFFLINE_MODEL_ONLY",production_authority=False,binding=binding,commands_issued=issued,paired_boundaries=paired,observed_boundary_bytes=consumed,first_divergence=first,final=last,processes=processes,elapsed_seconds=time.perf_counter()-start)
    path=folder/"receipt.json";path.write_text(json.dumps(result,indent=2)+"\n",encoding="utf-8")
    if expected_divergence:
        require(first is not None and first["step"]==1 and issued==1 and "reference" in first,"injected semantic fault not caught first: "+str(path))
        require(first["reference"]["values"]==first["candidate"]["values"] and first["reference"]["effects"]!=first["candidate"]["effects"],"fault did not isolate effects")
    else:require(first is None,"first divergence preserved: "+str(path))
    return dict(name=name,receipt=str(path),sha256=file_sha(path),paired_boundaries=paired,final=last)

def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--java-home",type=Path,required=True);parser.add_argument("--cargo",type=Path,required=True);parser.add_argument("--output",type=Path,required=True)
    args=parser.parse_args();folder=args.output.resolve()/uuid.uuid4().hex;folder.mkdir(parents=True,exist_ok=False)
    suffix=".exe" if os.name=="nt" else ""
    java=(args.java_home/"bin"/("java"+suffix)).resolve(strict=True);javac=(args.java_home/"bin"/("javac"+suffix)).resolve(strict=True);cargo=args.cargo.resolve(strict=True)
    sources={str(p):file_sha(p) for p in [HERE/"Cargo.toml",HERE/"Cargo.lock",TRANSPORT,*HERE.glob("*.py"),*HERE.glob("src/*.rs"),*HERE.glob("java/*.java")]}
    tools={str(p):file_sha(p) for p in (java,javac,cargo,Path(sys.executable))};checks=[];start=time.perf_counter()
    def check(command,label):
        t=time.perf_counter();p=subprocess.run(list(map(str,command)),cwd=HERE,shell=False,capture_output=True,text=True,timeout=120)
        for stream in ("stdout","stderr"):(folder/(label+"."+stream+".txt")).write_text(getattr(p,stream),encoding="utf-8")
        checks.append(dict(name=label,argv=list(map(str,command)),exit=p.returncode,elapsed_seconds=time.perf_counter()-t,stdout_sha256=file_sha(folder/(label+".stdout.txt")),stderr_sha256=file_sha(folder/(label+".stderr.txt"))))
        require(p.returncode==0,"build/test failed; preserved logs at "+str(folder))
    target=folder/"cargo-target";classes=folder/"classes";classes.mkdir()
    check([cargo,"fmt","--","--check"],"rust-fmt")
    check([cargo,"test","--locked","--offline","--target-dir",target],"rust-tests")
    check([cargo,"clippy","--locked","--offline","--target-dir",target,"--","-D","warnings"],"rust-clippy")
    check([cargo,"build","--release","--locked","--offline","--target-dir",target],"rust-build")
    check([javac,"-encoding","UTF-8","-d",classes,HERE/"java/StateDiffReference.java"],"java-build")
    reference=[str(java),"-cp",str(classes),"StateDiffReference"];candidate=[str(target/"release"/("state-diff-experiment"+suffix))]
    artifacts={str(p):file_sha(p) for p in [Path(candidate[0]),*classes.rglob("*.class")]};cases=[]
    def case(name,commands,values=None):
        result=run_case(name,commands,values or [0]*16,reference,candidate,folder/"cases");cases.append(result);return result["final"]
    final=case("gradient-copy-add-golden",["GRADIENT 3 3 9 -2","COPY 3 0","ADD 0 4"])
    require(final["values"][:6]==[13,0,0,9,7,5] and final["generation"]==3,"golden state mismatch")
    final=case("gradient-range-failure-is-atomic",["GRADIENT 0 3 65534 1"])
    require(final["status"]=="REJECTED" and final["values"]==[0]*16 and final["generation"]==0,"gradient failure published partial state")
    final=case("failure-then-valid-retry",["ADD 0 -1","ADD 0 2"])
    require(final["values"][0]==2 and final["generation"]==1,"retry mismatch")
    final=case("effect-order-golden",["GRADIENT 4 3 2 3"])
    require(final["effects"]==[[4,0,2],[5,0,5],[6,0,8]],"effect order mismatch")
    for name,command,error in (("invalid-cell","ADD 16 1","CELL"),("empty-gradient","GRADIENT 0 0 0 1","COUNT"),("integer-add-overflow","ADD 0 2147483647","RANGE")):
        final=case(name,[command],[1]*16);require(final["error"]==error and final["generation"]==0,"rejection mismatch")
    rng=random.Random(0x225B)
    for i in range(16):
        commands=[]
        for _ in range(32):
            index=rng.randrange(16)
            commands.append(rng.choice(["ADD %d %d"%(index,rng.randint(-1000,1000)),"COPY %d %d"%(index,rng.randrange(16)),"GRADIENT %d %d %d %d"%(index,rng.randint(1,16-index),rng.randrange(65536),rng.randint(-100,100))]))
        case("seeded-pure-trace-"+str(i),commands,[rng.randrange(65536) for _ in range(16)])
    cases.append(run_case("first-divergence-effect-only-fault",["ADD 0 1","ADD 0 2","COPY 0 1"],[0]*16,reference,candidate+["--fault-effect-receipt"],folder/"cases",expected_divergence=True))
    unchanged=all(file_sha(Path(p))==v for group in (sources,tools,artifacts) for p,v in group.items());require(unchanged,"source/tool/build drift")
    receipt=dict(schema="STATE_DIFF_CAMPAIGN_V1",status="PASS",decision="LIMITED_USE",scope="OFFLINE_MODEL_ONLY",production_authority=False,sources=sources,tools=tools,artifacts=artifacts,checks=checks,cases=cases,case_count=len(cases),paired_boundaries=sum(c["paired_boundaries"] for c in cases),all_inputs_unchanged=unchanged,elapsed_seconds=time.perf_counter()-start,limitations=["No Minecraft or Forge qualification","No arbitrary callbacks, IO, RNG-visible behavior or concurrent scheduler","Model admission is not a live runtime certificate","No performance speedup claim"])
    path=folder/"campaign.json";path.write_text(json.dumps(receipt,indent=2)+"\n",encoding="utf-8")
    print(json.dumps(dict(status="PASS",cases=len(cases),receipt=str(path),sha256=file_sha(path))))

if __name__=="__main__":main()
